/** Returns the best available translation for a locale. */
export function translator(locale: Locale): (key: TranslationKey) => string {
  const base = locale.split('-')[0];
  const table = TRANSLATIONS[locale] ?? TRANSLATIONS[base] ?? {};
  const fallback = TRANSLATIONS.en!;
  return (key) => table[key] ?? fallback[key] ?? key;
}

/** Honest coverage: how many keys are translated in the selected locale. */
export function translationCoverage(locale: Locale): number {
  const base = locale.split('-')[0];
  const table = TRANSLATIONS[locale] ?? TRANSLATIONS[base] ?? {};
  const keys = Object.keys(TRANSLATIONS.en ?? {}) as TranslationKey[];
  return Math.round((keys.filter((k) => !!table[k]).length / keys.length) * 100);
}
